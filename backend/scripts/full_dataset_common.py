from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
from typing import Any

from sqlalchemy import inspect, text
from sqlalchemy.engine import Engine, make_url

REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
MANIFEST_PATH = REPOSITORY_ROOT / "data" / "generated" / "manifest.json"
DATASET_PATH = REPOSITORY_ROOT / "data" / "generated" / "seed_data.jsonl.gz"
EXPECTED_DATABASE = "credential_fullscale_integration"
EXPECTED_ALEMBIC_REVISION = "af6e5dad6637"


def full_dataset_database_url(*, require_confirmation: bool) -> str:
    value = os.environ.get("FULL_DATASET_DATABASE_URL")
    if not value:
        raise RuntimeError(
            "Set FULL_DATASET_DATABASE_URL to the isolated full-scale integration database."
        )
    parsed = make_url(value)
    if parsed.get_backend_name() != "postgresql":
        raise RuntimeError("The full-dataset integration database must use PostgreSQL.")
    if parsed.database != EXPECTED_DATABASE:
        raise RuntimeError(
            f"Refusing database {parsed.database!r}; the required isolated database name is "
            f"{EXPECTED_DATABASE!r}."
        )
    if require_confirmation and os.environ.get("CONFIRM_FULL_DATASET_IMPORT") != "YES":
        raise RuntimeError(
            "Set CONFIRM_FULL_DATASET_IMPORT=YES only for the newly created disposable database."
        )
    return value


def load_and_validate_manifest(
    manifest_path: Path = MANIFEST_PATH,
    dataset_path: Path = DATASET_PATH,
) -> tuple[dict[str, Any], dict[str, Any]]:
    def file_digest(path: Path) -> str:
        digest = hashlib.sha256()
        with path.open("rb") as stream:
            for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                digest.update(chunk)
        return digest.hexdigest()

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("profile") != "full" or manifest.get("seed") != 20261022:
        raise ValueError("The source manifest is not the expected full profile and seed.")
    if manifest.get("dataset") != "synthetic":
        raise ValueError("The operational export must declare synthetic provenance.")
    if file_digest(dataset_path) != manifest.get("seed_data_sha256"):
        raise ValueError("Compressed dataset SHA-256 does not match its manifest.")

    source_manifest_path = manifest_path.parent / manifest["source_manifest"]
    source_bytes = source_manifest_path.read_bytes()
    if hashlib.sha256(source_bytes).hexdigest() != manifest.get(
        "source_manifest_sha256"
    ):
        raise ValueError("Source-manifest SHA-256 does not match the dataset manifest.")
    source_manifest = json.loads(source_bytes)
    if source_manifest.get("provenance") != (
        "Generated by this repository; no external data sources used."
    ):
        raise ValueError("Source manifest does not declare repository-only provenance.")
    source_file_drift = []
    for relative_path, expected_hash in source_manifest.get("source_files", {}).items():
        source_path = REPOSITORY_ROOT / relative_path
        if not source_path.is_file():
            source_file_drift.append(relative_path)
        elif file_digest(source_path) != expected_hash:
            source_file_drift.append(relative_path)
    source_manifest["source_file_checksum_mismatches"] = source_file_drift
    return manifest, source_manifest


def require_migrated_schema(engine: Engine, table_names: set[str]) -> None:
    existing = set(inspect(engine).get_table_names())
    missing = table_names - existing
    if missing:
        raise RuntimeError(
            "Apply the existing Alembic migration first; missing tables: "
            + ", ".join(sorted(missing))
        )
    with engine.connect() as connection:
        revisions = connection.execute(text("SELECT version_num FROM alembic_version")).scalars().all()
    if revisions != [EXPECTED_ALEMBIC_REVISION]:
        raise RuntimeError(
            f"Expected Alembic revision {EXPECTED_ALEMBIC_REVISION}; found {revisions!r}."
        )


def table_row_counts(engine: Engine, metadata: Any) -> dict[str, int]:
    from sqlalchemy import func, select

    counts: dict[str, int] = {}
    with engine.connect() as connection:
        for name, table in sorted(metadata.tables.items()):
            counts[name] = int(
                connection.execute(select(func.count()).select_from(table)).scalar_one()
            )
    return counts
